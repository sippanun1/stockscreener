-- DASHBOARD STATS
CREATE OR REPLACE FUNCTION public.get_dashboard_stats(p_market TEXT DEFAULT NULL, p_date DATE DEFAULT NULL) 
RETURNS JSON LANGUAGE plpgsql AS $$
DECLARE 
    result JSON;
    v_base_date DATE := COALESCE(p_date, CURRENT_DATE);
BEGIN
    IF p_date IS NULL OR p_date >= (CURRENT_DATE - INTERVAL '1 day') THEN
        WITH Filtered AS (
            SELECT technical_rating, fetched_date
            FROM public.latest_stock_ratings l
            WHERE (p_market IS NULL OR p_market = '' OR l.market = p_market)
            AND l.symbol NOT LIKE 'OTC:%'
            AND l.current_price >= 0.2 
        )
        SELECT json_build_object(
            'total_positive', COUNT(*) FILTER (WHERE technical_rating IN ('Strong Buy', 'Buy')),
            'total_negative', COUNT(*) FILTER (WHERE technical_rating IN ('Strong Sell', 'Sell')),
            'strong_buy', COUNT(*) FILTER (WHERE technical_rating = 'Strong Buy'),
            'buy', COUNT(*) FILTER (WHERE technical_rating = 'Buy'),
            'strong_sell', COUNT(*) FILTER (WHERE technical_rating = 'Strong Sell'),
            'sell', COUNT(*) FILTER (WHERE technical_rating = 'Sell'),
            'neutral', COUNT(*) FILTER (WHERE technical_rating = 'Neutral'),
            'date', MAX(fetched_date) 
        ) INTO result
        FROM Filtered;
    ELSE
        WITH LatestPerSymbol AS (
            SELECT DISTINCT ON (sr.symbol) technical_rating, fetched_date, current_price, market
            FROM public.stock_ratings sr
            WHERE sr.fetched_date >= (v_base_date - INTERVAL '60 days') AND sr.fetched_date <= v_base_date
            ORDER BY sr.symbol, sr.fetched_date DESC, sr.fetched_time DESC
        )
        SELECT json_build_object(
            'total_positive', COUNT(*) FILTER (WHERE technical_rating IN ('Strong Buy', 'Buy')),
            'total_negative', COUNT(*) FILTER (WHERE technical_rating IN ('Strong Sell', 'Sell')),
            'strong_buy', COUNT(*) FILTER (WHERE technical_rating = 'Strong Buy'),
            'buy', COUNT(*) FILTER (WHERE technical_rating = 'Buy'),
            'strong_sell', COUNT(*) FILTER (WHERE technical_rating = 'Strong Sell'),
            'sell', COUNT(*) FILTER (WHERE technical_rating = 'Sell'),
            'neutral', COUNT(*) FILTER (WHERE technical_rating = 'Neutral'),
            'date', MAX(fetched_date) 
        ) INTO result
        FROM LatestPerSymbol l
        WHERE (p_market IS NULL OR p_market = '' OR l.market = p_market)
        AND l.current_price >= 0.2;
    END IF;
    RETURN result;
END; $$;

