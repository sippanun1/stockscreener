-- Trigger B: Auto Calculate Metrics (Change %, Amount)
CREATE OR REPLACE FUNCTION public.calculate_daily_metrics()
RETURNS TRIGGER AS $$
DECLARE
    prev_record RECORD;
BEGIN
    IF NEW.daily_change_percent IS NULL OR NEW.prev_close_price IS NULL THEN
        SELECT current_price INTO prev_record
        FROM public.stock_ratings
        WHERE symbol = NEW.symbol
        AND (fetched_date < NEW.fetched_date OR (fetched_date = NEW.fetched_date AND fetched_time < NEW.fetched_time))
        ORDER BY fetched_date DESC, fetched_time DESC
        LIMIT 1;

        IF FOUND THEN
            NEW.prev_close_price := prev_record.current_price;
            IF NEW.daily_change_percent IS NULL AND NEW.prev_close_price > 0 THEN
                NEW.daily_change_percent := ((NEW.current_price - NEW.prev_close_price) / NEW.prev_close_price * 100);
                NEW.daily_change_amount := (NEW.current_price - NEW.prev_close_price);
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_calculate_daily_metrics ON public.stock_ratings;
CREATE TRIGGER trigger_calculate_daily_metrics
    BEFORE INSERT OR UPDATE ON public.stock_ratings  -- Fire on upsert too
    FOR EACH ROW
    EXECUTE FUNCTION public.calculate_daily_metrics();

-- Trigger C: Auto Calculate Rating Change Date
-- UPDATED: Include Neutral Skip Logic (Look back to last non-neutral)
CREATE OR REPLACE FUNCTION public.auto_calculate_rating_date()
RETURNS TRIGGER AS $$
DECLARE
    last_record RECORD;
BEGIN
    IF NEW.technical_rating = 'Neutral' THEN
        -- If this new record IS Neutral, we don't strictly care about its "previous" 
        -- logic for signals, but we should populate it for completeness.
        -- It references the last non-neutral rating.
        SELECT technical_rating, rating_change_date, previous_rating, previous_rating_date
        INTO last_record
        FROM public.stock_ratings
        WHERE symbol = NEW.symbol
          AND technical_rating != 'Neutral' -- Ignore other Neutrals
        ORDER BY fetched_date DESC, fetched_time DESC
        LIMIT 1;

        IF NOT FOUND THEN
            NEW.rating_change_date := NEW.fetched_date;
            NEW.previous_rating := NULL;
            NEW.previous_rating_date := NULL;
        ELSE
             -- It's Neutral, so effective rating "change" doesn't strictly tick for signal logic,
             -- but for the record itself:
             NEW.rating_change_date := last_record.rating_change_date;
             NEW.previous_rating := last_record.technical_rating;
             NEW.previous_rating_date := last_record.rating_change_date;
        END IF;

    ELSE
        -- If this new record is NOT Neutral (Buy/Sell), find the last NON-NEUTRAL record
        SELECT technical_rating, rating_change_date, previous_rating, previous_rating_date
        INTO last_record
        FROM public.stock_ratings
        WHERE symbol = NEW.symbol
          AND technical_rating != 'Neutral'
        ORDER BY fetched_date DESC, fetched_time DESC
        LIMIT 1;

        IF NOT FOUND THEN
            -- First non-neutral signal
            NEW.rating_change_date := NEW.fetched_date;
            NEW.previous_rating := NULL;
            NEW.previous_rating_date := NULL;
        ELSIF last_record.technical_rating != NEW.technical_rating THEN
            -- Rating CHANGED (e.g. Sell -> ... -> Buy)
            NEW.rating_change_date := NEW.fetched_date;
            NEW.previous_rating := last_record.technical_rating;
            NEW.previous_rating_date := last_record.rating_change_date;
        ELSE
            -- Rating stayed the SAME (e.g. Buy -> ... -> Buy)
            NEW.rating_change_date := last_record.rating_change_date;
            NEW.previous_rating := last_record.previous_rating;
            NEW.previous_rating_date := last_record.previous_rating_date;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_calc_rating_date ON public.stock_ratings;
CREATE TRIGGER trigger_calc_rating_date
BEFORE INSERT ON public.stock_ratings
FOR EACH ROW
EXECUTE FUNCTION public.auto_calculate_rating_date();

