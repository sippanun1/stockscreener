-- Trigger A: Sync to 'latest_stock_ratings' (Achieves INSTANT Loading)
-- UPDATED: Includes "Neutral Skip" Logic (Latch latest valid rating)
CREATE OR REPLACE FUNCTION public.sync_latest_stock_rating()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.technical_rating = 'Neutral' THEN
        -- "Keep it the same buy -> sell" logic.
        -- If new is Neutral, only update Price/Date info, but RETAIN the old Rating info.
        UPDATE public.latest_stock_ratings SET
            current_price = NEW.current_price,
            open = NEW.open,
            premarket_close = NEW.premarket_close,
            premarket_open = NEW.premarket_open,
            postmarket_close = NEW.postmarket_close,
            postmarket_open = NEW.postmarket_open,
            technical_score = NEW.technical_score,
            -- DO NOT update technical_rating
            fetched_date = NEW.fetched_date,
            fetched_time = NEW.fetched_time,
            session_type = NEW.session_type,
            -- DO NOT update rating_change_date, previous_rating, etc.
            prev_close_price = NEW.prev_close_price,
            daily_change_percent = NEW.daily_change_percent,
            daily_change_amount = NEW.daily_change_amount,
            accuracy_percent = COALESCE(NEW.accuracy_percent, (SELECT accuracy_percent FROM public.latest_stock_ratings WHERE symbol = NEW.symbol)), -- Preserve old accuracy
            updated_at = NOW()
        WHERE symbol = NEW.symbol;
        
        -- If it doesn't exist yet (First record is Neutral), we insert it as Neutral
        IF NOT FOUND THEN
             INSERT INTO public.latest_stock_ratings (
                symbol, id, market, name, current_price, open, 
                premarket_close, premarket_open, postmarket_close, postmarket_open,
                sector, industry, technical_score, technical_rating,
                fetched_date, fetched_time, session_type, rating_change_date,
                prev_close_price, daily_change_percent, daily_change_amount,
                previous_rating, previous_rating_date, accuracy_percent,
                updated_at
            )
            VALUES (
                NEW.symbol, NEW.id, NEW.market, NEW.name, NEW.current_price, NEW.open,
                NEW.premarket_close, NEW.premarket_open, NEW.postmarket_close, NEW.postmarket_open,
                NEW.sector, NEW.industry, NEW.technical_score, NEW.technical_rating,
                NEW.fetched_date, NEW.fetched_time, NEW.session_type, NEW.rating_change_date,
                NEW.prev_close_price, NEW.daily_change_percent, NEW.daily_change_amount,
                NEW.previous_rating, NEW.previous_rating_date, NEW.accuracy_percent,
                NOW()
            );
        END IF;

    ELSE
        -- Normal Update (Non-Neutral) - Overwrite everything including Rating
        INSERT INTO public.latest_stock_ratings (
            symbol, id, market, name, current_price, open, 
            premarket_close, premarket_open, postmarket_close, postmarket_open,
            sector, industry, technical_score, technical_rating,
            fetched_date, fetched_time, session_type, rating_change_date,
            prev_close_price, daily_change_percent, daily_change_amount,
            previous_rating, previous_rating_date, accuracy_percent,
            updated_at
        )
        VALUES (
            NEW.symbol, NEW.id, NEW.market, NEW.name, NEW.current_price, NEW.open,
            NEW.premarket_close, NEW.premarket_open, NEW.postmarket_close, NEW.postmarket_open,
            NEW.sector, NEW.industry, NEW.technical_score, NEW.technical_rating,
            NEW.fetched_date, NEW.fetched_time, NEW.session_type, NEW.rating_change_date,
            NEW.prev_close_price, NEW.daily_change_percent, NEW.daily_change_amount,
            NEW.previous_rating, NEW.previous_rating_date, NEW.accuracy_percent,
            NOW()
        )
        ON CONFLICT (symbol) DO UPDATE SET
            id = EXCLUDED.id,
            current_price = EXCLUDED.current_price,
            technical_score = EXCLUDED.technical_score,
            technical_rating = EXCLUDED.technical_rating, -- Update Rating
            fetched_date = EXCLUDED.fetched_date,
            fetched_time = EXCLUDED.fetched_time,
            rating_change_date = EXCLUDED.rating_change_date, -- Update Dates
            daily_change_percent = EXCLUDED.daily_change_percent,
            daily_change_amount = EXCLUDED.daily_change_amount,
            previous_rating = EXCLUDED.previous_rating, -- Update Prev
            previous_rating_date = EXCLUDED.previous_rating_date,
            -- Preserve old accuracy if new data doesn't have it yet
            accuracy_percent = COALESCE(EXCLUDED.accuracy_percent, latest_stock_ratings.accuracy_percent),
            total_signals = COALESCE(EXCLUDED.total_signals, latest_stock_ratings.total_signals),
            updated_at = NOW()
        WHERE (EXCLUDED.fetched_date > latest_stock_ratings.fetched_date) 
           OR (EXCLUDED.fetched_date = latest_stock_ratings.fetched_date AND EXCLUDED.fetched_time >= latest_stock_ratings.fetched_time);
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

