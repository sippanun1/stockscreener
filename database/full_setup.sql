-- Function to recalculate rating history for a specific symbol (Neutral Skip Logic)
CREATE OR REPLACE FUNCTION public.recalculate_symbol_history(p_symbol TEXT)
RETURNS VOID AS $$
DECLARE
    r RECORD;
    curr_rating TEXT := NULL;
    curr_change_date DATE := NULL;
    prev_rating TEXT := NULL;
    prev_rating_date DATE := NULL;
BEGIN
    FOR r IN
        SELECT id, fetched_date, technical_rating, fetched_time
        FROM public.stock_ratings
        WHERE symbol = p_symbol
        ORDER BY fetched_date ASC, fetched_time ASC
    LOOP
        -- If Neutral, SKIP logic for signal state (keep valid) but update row pointers
        IF r.technical_rating = 'Neutral' THEN
             UPDATE public.stock_ratings
             SET rating_change_date = curr_change_date,
                 previous_rating = prev_rating,
                 previous_rating_date = prev_rating_date
             WHERE id = r.id;
        ELSE
            -- Non-Neutral (Buy/Sell)
            IF curr_rating IS NULL THEN
                curr_rating := r.technical_rating;
                curr_change_date := r.fetched_date;
                prev_rating := NULL;
                prev_rating_date := NULL;
                
                UPDATE public.stock_ratings
                SET rating_change_date = curr_change_date,
                    previous_rating = NULL,
                    previous_rating_date = NULL
                WHERE id = r.id;
                
            ELSIF r.technical_rating != curr_rating THEN
                -- Change Detected
                prev_rating := curr_rating;
                prev_rating_date := curr_change_date;
                
                curr_rating := r.technical_rating;
                curr_change_date := r.fetched_date;
                
                UPDATE public.stock_ratings
                SET rating_change_date = curr_change_date,
                    previous_rating = prev_rating,
                    previous_rating_date = prev_rating_date
                WHERE id = r.id;
            ELSE
                -- Same Rating
                UPDATE public.stock_ratings
                SET rating_change_date = curr_change_date,
                    previous_rating = prev_rating,
                    previous_rating_date = prev_rating_date
                WHERE id = r.id;
            END IF;
        END IF;
    END LOOP;
    
    PERFORM public.sync_latest_stock_rating_manual(p_symbol);
END;
$$ LANGUAGE plpgsql;

-- Manual Sync with Neutral Skip Logic
-- MUST MATCH TRIGGER LOGIC: Latch to last VALID rating
CREATE OR REPLACE FUNCTION public.sync_latest_stock_rating_manual(p_symbol TEXT)
RETURNS VOID AS $$
DECLARE
    latest_valid_rec RECORD;
    latest_real_rec RECORD;
BEGIN
    SELECT * INTO latest_valid_rec
    FROM public.stock_ratings
    WHERE symbol = p_symbol AND technical_rating != 'Neutral'
    ORDER BY fetched_date DESC, fetched_time DESC
    LIMIT 1;

    SELECT * INTO latest_real_rec
    FROM public.stock_ratings
    WHERE symbol = p_symbol
    ORDER BY fetched_date DESC, fetched_time DESC
    LIMIT 1;
    
    IF FOUND THEN
        IF latest_valid_rec IS NULL THEN
            latest_valid_rec := latest_real_rec;
